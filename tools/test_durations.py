#!/usr/bin/env python3
"""Report test durations from a .trx file and refresh the slow-test list.

Usage:
  python3 tools/test_durations.py RESULTS.trx [--top 25] [--update-slow-list SECONDS]

The slow list (tools/slow_tests.txt) holds one test class per line whose slowest test
takes at least the threshold. tools/ci_quick.sh excludes those classes; the full
tools/ci_check.sh (and GitHub Actions) still run every test.
"""
import argparse
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SLOW_LIST = Path(__file__).with_name("slow_tests.txt")
NS = {"t": "http://microsoft.com/schemas/VisualStudio/TeamTest/2010"}


def seconds(duration: str) -> float:
    h, m, s = duration.split(":")
    return int(h) * 3600 + int(m) * 60 + float(s)


def test_class(name: str) -> str:
    # "Namespace.Class.Method(args)" -> "Namespace.Class"
    return re.sub(r"\(.*\)$", "", name).rsplit(".", 1)[0]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("trx")
    parser.add_argument("--top", type=int, default=25)
    parser.add_argument("--update-slow-list", type=float, metavar="SECONDS")
    args = parser.parse_args()

    root = ET.parse(args.trx).getroot()
    results = []
    for result in root.iterfind(".//t:UnitTestResult", NS):
        duration = result.get("duration")
        if duration:
            results.append((seconds(duration), result.get("testName", "?"), result.get("outcome", "?")))
    if not results:
        print("no test results with durations", file=sys.stderr)
        return 1
    results.sort(reverse=True)
    total = sum(r[0] for r in results)
    print(f"{len(results)} tests, {total / 60:.1f} CPU-minutes in test bodies")
    for duration, name, outcome in results[: args.top]:
        print(f"{duration:8.1f} s  {outcome:7s}  {name}")

    by_class: dict[str, float] = {}
    for duration, name, _ in results:
        cls = test_class(name)
        by_class[cls] = by_class.get(cls, 0.0) + duration
    print("\nslowest classes (summed):")
    for cls, duration in sorted(by_class.items(), key=lambda kv: -kv[1])[:15]:
        print(f"{duration:8.1f} s  {cls}")

    if args.update_slow_list is not None:
        slow = sorted({test_class(name) for duration, name, _ in results if duration >= args.update_slow_list})
        SLOW_LIST.write_text(
            f"# Test classes with a test of at least {args.update_slow_list:g} s; generated by\n"
            f"# tools/test_durations.py from a full-suite .trx. tools/ci_quick.sh skips them.\n"
            + "".join(f"{cls}\n" for cls in slow))
        print(f"\nwrote {len(slow)} classes to {SLOW_LIST}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
