#!/usr/bin/env python3
"""Builds docs/physics/estimates_register.md from data/provenance/*.json.

The register lists every value that is NOT published hardware/mission data (estimated,
calibrated, derived, unknown, regulatory envelope), grouped by status, so historical
recalibration (fidelity phase F6) knows exactly what is still a model choice.

    python3 tools/provenance_register.py          # rewrite the register
    python3 tools/provenance_register.py --check  # fail if the register is stale
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "data" / "provenance"
TARGET = ROOT / "docs" / "physics" / "estimates_register.md"
ORDER = ["calibrated", "estimated", "derived", "unknown", "regulatory_envelope", "regulatoryenvelope"]


def cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def build() -> str:
    records = []
    counts = {}
    for path in sorted(SOURCE.glob("*.json")):
        manifest = json.loads(path.read_text(encoding="utf-8"))
        for record in manifest.get("records", []):
            status = str(record.get("status", "")).lower()
            counts[status] = counts.get(status, 0) + 1
            if status == "published":
                continue
            records.append((path.name, record, status))
    lines = [
        "# Estimates register",
        "",
        "Generated by `tools/provenance_register.py` from `data/provenance/*.json`; do not edit by hand.",
        "Every value below is a model choice rather than published hardware or mission data. Historical",
        "recalibration (fidelity phase F6) works through this list; a value leaves it only when its",
        "provenance record is upgraded to `published` with a cited source.",
        "",
        "| Status | Records |",
        "| --- | ---: |",
    ]
    for status in sorted(counts, key=lambda s: (ORDER.index(s) if s in ORDER else 99, s)):
        lines.append(f"| {status} | {counts[status]} |")
    for status in sorted({s for _, _, s in records}, key=lambda s: (ORDER.index(s) if s in ORDER else 99, s)):
        lines += ["", f"## {status}", "", "| Data | Field | Value | Uncertainty | Source | Manifest |", "| --- | --- | ---: | --- | --- | --- |"]
        for manifest, record, s in sorted(records, key=lambda r: (r[1]["dataId"], r[1]["field"])):
            if s != status:
                continue
            value = record.get("value")
            lines.append("| " + " | ".join([
                cell(record["dataId"]), cell(record["field"]),
                "" if value is None else cell(f"{value:g}"),
                cell(record.get("uncertainty", "")), cell(record.get("source", "")), cell(manifest)]) + " |")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv[1:]:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print("estimates register is stale: run python3 tools/provenance_register.py", file=sys.stderr)
            return 1
        print("provenance_register: up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
